"""M2 — Diffusion-TS-inspired decomposition baseline.

Reference
---------
Zhou et al. (2023). "Diffusion-TS: Interpretable Time Series Forecasting
with Diffusion Models." https://arxiv.org/abs/2311.14160

Core idea
---------
Decompose a water-level series into trend + seasonal + residual.
Fit trend via moving-average low-pass filter, seasonal via FFT on the
known tidal periods (12 h M2, 24 h K1/O1), and apply diffusion *only*
to the residual component. The trend and seasonal are extrapolated
deterministically; the residual is generated by DDPM.

For TideTail (96 h history → 72 h forecast, standardized residuals):
  x = trend + seasonal + residual
  forecast = trend_extrap + seasonal_extrap + residual_ddpm

This is NOT a faithful reproduction of Diffusion-TS; it is a
TideTail-specific decomposition baseline that isolates how much of
the extreme-value distribution comes from residuals vs. the
deterministic components.
"""
from __future__ import annotations

import math
from collections.abc import Sequence

import torch
import torch.nn.functional as F
from torch import nn

from ..torch_diffusion import Diffusion

# ---------------------------------------------------------------------------
# Deterministic decomposition
# ---------------------------------------------------------------------------

def moving_average_trend(x: torch.Tensor, window: int = 24) -> torch.Tensor:
    """Low-pass trend via causal moving average, left-padded with first value.

    Args:
        x: shape (batch, time)
        window: averaging window in hourly steps (default 24 h ≈ K1 tidal day)

    Returns:
        trend: same shape as x
    """
    if window < 1 or x.shape[1] < window:
        raise ValueError(f"invalid window {window} for length {x.shape[1]}")
    # Causal pad: repeat first value so output is aligned with input
    left = x[:, :1].repeat(1, window - 1)
    padded = torch.cat([left, x], dim=1)
    kernel = torch.ones(window, device=x.device, dtype=x.dtype) / window
    trend = F.conv1d(padded.unsqueeze(1), kernel.view(1, 1, window)).squeeze(1)
    # Conv output is len(padded) - window + 1 = len(x) ✓
    return trend


def fft_seasonal(x: torch.Tensor,
                 periods: Sequence[float] = (12.0, 24.0)) -> torch.Tensor:
    """Seasonal component via sinusoidal regression on known tidal periods.

    Fits ``sum_p A_p * sin(2π t / p + φ_p) + C`` independently per batch
    element using least squares. No window/de-window artefacts, stable
    at all signal-to-noise levels.

    Args:
        x: shape (batch, time), hourly samples
        periods: tidal periods in hours. Defaults to M2 (12h) + K1/O1 (24h).

    Returns:
        seasonal: same shape as x
    """
    _B, T = x.shape
    if T < 4:
        raise ValueError(f"need at least 4 points, got {T}")
    t = torch.arange(T, device=x.device, dtype=x.dtype)
    # Build design matrix: [const, sin(2πt/p1), cos(2πt/p1), ...]
    cols = [torch.ones(T, device=x.device, dtype=x.dtype)]
    for p in periods:
        omega = 2 * math.pi / p
        cols.append(torch.sin(omega * t))
        cols.append(torch.cos(omega * t))
    A = torch.stack(cols, dim=1)  # (T, K)
    # Solve normal equations: (A^T A) θ = A^T x  →  θ = (A^T A)^-1 A^T x
    AtA = A.T @ A
    AtX = x @ A  # (B, K)
    theta = torch.linalg.solve(AtA, AtX.T).T  # (B, K)
    # Reconstruct: seasonal = A @ theta.T
    seasonal = (A @ theta.T).T
    return seasonal


def decompose(x: torch.Tensor, trend_window: int = 24,
              seasonal_periods: Sequence[float] = (12.0, 24.0)):
    """Return (trend, seasonal, residual) for hourly water-level series."""
    trend = moving_average_trend(x, window=trend_window)
    seasonal = fft_seasonal(x, periods=seasonal_periods)
    residual = x - trend - seasonal
    return trend, seasonal, residual


def extrapolate_trend(history_trend: torch.Tensor, horizon: int) -> torch.Tensor:
    """Linear extrapolation of the trend segment over the forecast horizon."""
    if history_trend.shape[1] < 2:
        return history_trend[:, :1].repeat(1, horizon)
    # Simple linear fit via last 24h
    n = min(24, history_trend.shape[1])
    recent = history_trend[:, -n:]
    torch.arange(n, device=history_trend.device, dtype=history_trend.dtype)
    slope = (recent[:, -1] - recent[:, 0]) / max(n - 1, 1)
    intercept = recent[:, -1]
    t_future = torch.arange(1, horizon + 1, device=history_trend.device,
                            dtype=history_trend.dtype)
    return intercept[:, None] + slope[:, None] * t_future[None, :]


def extrapolate_seasonal(history_seasonal: torch.Tensor, horizon: int,
                         periods: Sequence[float] = (12.0, 24.0),
                         period_hours: float | None = None) -> torch.Tensor:
    """Seasonal extrapolation via refitting sinusoids on history.

    Uses the same least-squares sinusoidal regression as
    :func:`fft_seasonal`, but evaluates the fit at future time points.
    If refitting fails (singular matrix), falls back to periodic tiling.
    """
    _B, T = history_seasonal.shape
    device = history_seasonal.device
    dtype = history_seasonal.dtype

    t_hist = torch.arange(T, device=device, dtype=dtype)
    t_future = torch.arange(T, T + horizon, device=device, dtype=dtype)

    cols_hist = [torch.ones(T, device=device, dtype=dtype)]
    cols_fut = [torch.ones(horizon, device=device, dtype=dtype)]
    for p in periods:
        omega = 2 * math.pi / p
        cols_hist.append(torch.sin(omega * t_hist))
        cols_hist.append(torch.cos(omega * t_hist))
        cols_fut.append(torch.sin(omega * t_future))
        cols_fut.append(torch.cos(omega * t_future))

    A_hist = torch.stack(cols_hist, dim=1)
    A_fut = torch.stack(cols_fut, dim=1)
    AtA = A_hist.T @ A_hist
    AtX = history_seasonal @ A_hist
    try:
        theta = torch.linalg.solve(AtA, AtX.T).T
        return (A_fut @ theta.T).T
    except torch.linalg.LinAlgError:
        # Fallback: periodic tile
        ph = period_hours or round(periods[0])
        if ph <= 0 or T < ph:
            return history_seasonal[:, -1:].repeat(1, horizon)
        last = history_seasonal[:, -ph:]
        repeats = (horizon // ph) + 2
        return last.repeat(1, repeats)[:, :horizon]


# ---------------------------------------------------------------------------
# Residual denoiser (reuse TemporalDenoiser architecture)
# ---------------------------------------------------------------------------

class ResidualDenoiser(nn.Module):
    """Small dilated TCN denoiser for the residual component.

    Same architecture as ``torch_diffusion.TemporalDenoiser`` but operates
    on the residual series only. Conditioned on *historical* residual and
    optionally on trend/seasonal context.
    """

    def __init__(self, context: int = 96, horizon: int = 72, width: int = 32,
                 use_full_context: bool = True):
        super().__init__()
        self.context = context
        self.horizon = horizon
        self.width = width
        self.use_full_context = use_full_context

        in_features = context * (3 if use_full_context else 1)
        self.history = nn.Sequential(
            nn.Linear(in_features, width), nn.SiLU(), nn.Linear(width, width)
        )
        self.time = nn.Sequential(
            nn.Linear(width, width), nn.SiLU(), nn.Linear(width, width)
        )
        self.input_proj = nn.Conv1d(1, width, 3, padding=1)
        self.blocks = nn.ModuleList([
            _ResBlock(width, d) for d in (1, 2, 4, 8, 16)
        ])
        self.output = nn.Sequential(
            nn.GroupNorm(4, width), nn.SiLU(), nn.Conv1d(width, 1, 3, padding=1)
        )

    def forward(self, noisy_residual: torch.Tensor, timestep: torch.Tensor,
                history_residual: torch.Tensor,
                history_trend: torch.Tensor | None = None,
                history_seasonal: torch.Tensor | None = None) -> torch.Tensor:
        """Predict epsilon on the residual component.

        Args:
            noisy_residual: (batch, 1, horizon) noisy residual at timestep
            timestep: (batch,) long tensor
            history_residual: (batch, context)
            history_trend: (batch, context) — optional full context
            history_seasonal: (batch, context) — optional full context
        """
        if noisy_residual.ndim != 3 or noisy_residual.shape[1:] != (1, self.horizon):
            raise ValueError(f"noisy_residual must be (batch, 1, {self.horizon})")
        noisy_residual.shape[0]

        # Time embedding (sinusoidal)
        freq = torch.exp(
            torch.arange(self.width // 2, device=noisy_residual.device)
            * (-math.log(10000) / max(self.width // 2 - 1, 1))
        )
        angles = timestep.float()[:, None] * freq[None]
        time_emb = self.time(torch.cat([angles.sin(), angles.cos()], dim=1))

        # History context embedding
        if self.use_full_context:
            assert history_trend is not None and history_seasonal is not None
            ctx = torch.cat([history_residual, history_trend, history_seasonal],
                            dim=1)
        else:
            ctx = history_residual
        hist_emb = self.history(ctx)

        embedding = time_emb + hist_emb

        x = self.input_proj(noisy_residual)
        for block in self.blocks:
            x = block(x, embedding)
        return self.output(x)


class _ResBlock(nn.Module):
    def __init__(self, width: int, dilation: int):
        super().__init__()
        self.net = nn.Sequential(
            nn.GroupNorm(4, width),
            nn.SiLU(),
            nn.Conv1d(width, width, 3, padding=dilation, dilation=dilation),
            nn.GroupNorm(4, width),
            nn.SiLU(),
            nn.Conv1d(width, width, 1),
        )
        self.cond = nn.Linear(width, width)

    def forward(self, x: torch.Tensor, emb: torch.Tensor) -> torch.Tensor:
        cond_bias = self.cond(emb)[:, :, None]
        return (x + self.net(x + cond_bias)) / math.sqrt(2)


# ---------------------------------------------------------------------------
# Full Diffusion-TS model (training + sampling)
# ---------------------------------------------------------------------------

class DiffusionTS:
    """Diffusion-TS decomposition model for 96h→72h tide forecasting.

    Usage:
        model = DiffusionTS(context=96, horizon=72, steps=64,
                            schedule="cosine1000_subsample")
        # Training:
        loss = model.training_loss(history_x, target_x)
        # Inference:
        forecast = model.forecast(history_x, denoiser, seed=42)
    """

    def __init__(self, context: int = 96, horizon: int = 72,
                 steps: int = 64,
                 schedule: str = "cosine1000_subsample",
                 trend_window: int = 24,
                 seasonal_periods: Sequence[float] = (12.0, 24.0),
                 device: str = "cpu"):
        self.context = context
        self.horizon = horizon
        self.diffusion = Diffusion(steps=steps, device=device, schedule=schedule)
        self.trend_window = trend_window
        self.seasonal_periods = tuple(seasonal_periods)
        self.device = device

    # --- Decomposition -------------------------------------------------------
    def decompose_history(self, x: torch.Tensor):
        """Decompose history (batch, context) into trend/seasonal/residual."""
        return decompose(x, trend_window=self.trend_window,
                         seasonal_periods=self.seasonal_periods)

    # --- Training loss -------------------------------------------------------
    def training_loss(self, history_x: torch.Tensor, target_x: torch.Tensor,
                      denoiser: nn.Module,
                      fourier_weight: float = 0.1) -> torch.Tensor:
        """Denoiser epsilon loss + optional Fourier spectrum matching.

        Residuals are z-score normalized *per-sample* using history
        statistics so that DDPM input (history residual) and target
        (target residual) live on the same scale.
        """
        B = history_x.shape[0]
        device = history_x.device

        hist_trend, hist_seasonal, hist_residual = self.decompose_history(history_x)
        _, _, tgt_residual = decompose(
            target_x, trend_window=self.trend_window,
            seasonal_periods=self.seasonal_periods
        )

        # Per-sample residual normalization (history stats → apply to both)
        res_mean = hist_residual.mean(dim=1, keepdim=True)
        res_std = hist_residual.std(dim=1, keepdim=True).clamp(min=1e-4)
        hist_res_norm = (hist_residual - res_mean) / res_std
        tgt_res_norm = (tgt_residual - res_mean) / res_std

        # Forward diffusion
        t = torch.randint(0, self.diffusion.steps, (B,), device=device)
        eps = torch.randn_like(tgt_res_norm)
        noisy = self.diffusion.noisy(tgt_res_norm.unsqueeze(1), t, eps.unsqueeze(1))

        eps_pred = denoiser(
            noisy, t,
            history_residual=hist_res_norm,
            history_trend=hist_trend,
            history_seasonal=hist_seasonal,
        ).squeeze(1)

        loss = F.mse_loss(eps_pred, eps)
        if fourier_weight > 0:
            pred_fft = torch.fft.rfft(eps_pred, dim=1).abs().log().clamp(-10, 10)
            tgt_fft = torch.fft.rfft(tgt_res_norm, dim=1).abs().log().clamp(-10, 10)
            loss = loss + fourier_weight * F.mse_loss(pred_fft, tgt_fft)
        return loss

    # --- Forecasting ---------------------------------------------------------
    @torch.no_grad()
    def forecast(self, history_x: torch.Tensor, denoiser: nn.Module,
                 seed: int = 42) -> torch.Tensor:
        """96h history → 72h forecast via decomposition + DDPM residual."""
        denoiser.eval()
        device = history_x.device

        hist_trend, hist_seasonal, hist_residual = self.decompose_history(history_x)

        # Residual normalization (same as training)
        res_mean = hist_residual.mean(dim=1, keepdim=True)
        res_std = hist_residual.std(dim=1, keepdim=True).clamp(min=1e-4)
        hist_res_norm = (hist_residual - res_mean) / res_std

        # Extrapolate deterministic components
        trend_future = extrapolate_trend(hist_trend, self.horizon)
        seasonal_future = extrapolate_seasonal(hist_seasonal, self.horizon,
                                                periods=self.seasonal_periods)

        # DDPM sample (in normalized residual space)
        rng = torch.Generator(device=device).manual_seed(seed)
        x_T = torch.randn((history_x.shape[0], 1, self.horizon),
                          device=device, generator=rng)
        for i in reversed(range(self.diffusion.steps)):
            t = torch.full((history_x.shape[0],), i, dtype=torch.long,
                           device=device)
            eps = denoiser(x_T, t, history_residual=hist_res_norm,
                           history_trend=hist_trend,
                           history_seasonal=hist_seasonal)
            x_T = (x_T - self.diffusion.beta[i]
                   / (1 - self.diffusion.bar[i]).sqrt() * eps)
            x_T = x_T / self.diffusion.alpha[i].sqrt()
            if i > 0:
                x_T = x_T + self.diffusion.posterior_variance[i].sqrt() \
                    * torch.randn_like(x_T, generator=rng)

        # Denormalize residual back to original scale
        residual_norm = x_T.squeeze(1)
        residual_future = residual_norm * res_std + res_mean

        return trend_future + seasonal_future + residual_future
